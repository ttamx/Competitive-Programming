#include<bits/stdc++.h>

using namespace std;


const int n=20;

int calc(int i,int x){
    if(i==19)return __builtin_popcount(x)&1;
    return x>>i&1;
}

void encode(){
    int k;
    cin >> k;
    k--;
    int c=0;
    for(int i=0;i<n;i++){
        int x;
        cin >> x;
        c^=calc(k,x);
    }
    cout << c << endl;
}

void decode(){
    int k;
    cin >> k;
    k--;
    vector<int> c(n);
    int sum=0;
    for(auto &x:c){
        cin >> x;
        sum^=x;
    }
    string s;
    cin >> s;
    int ans=0,cnt=0;
    int tot=0;
    for(int i=0;i<n;i++){
        if(i==k)continue;
        int t=calc(i,c[i])^(s[i]=='1');
        if(i==19){
            cnt=t;
        }else{
            tot^=t<<i;
        }
    }
    if(k!=19){
        if(calc(19,tot)!=cnt){
            tot^=1<<k;
        }
    }
    cout << (sum^tot) << endl;
}

int main(){
    cin.tie(nullptr)->sync_with_stdio(false);
    int t;
    cin >> t;
    while(t--)encode();
    cin >> t;
    while(t--)decode();
}

