void runcase(){
    int n,m;
    cin >> n >> m;
    vector<vector<int>> adj(n);
    for(int i=0;i<m;i++){
        int u,v;
        cin >> u >> v;
        u--,v--;
        adj[u].emplace_back(v);
        adj[v].emplace_back(u);
    }
    vector<int> d(n,-1);
    queue<int> q;
    q.emplace(0);
    d[0]=0;
    while(!q.empty()){
        int u=q.front();
        q.pop();
        for(auto v:adj[u]){
            if(d[v]==-1){
                d[v]=d[u]+1;
                q.emplace(v);
            }else if((d[v]+d[u])%2==0){
                cout << -1 << "\n";
                return;
            }
        }
    }
    cout << d[n-1] << "\n";
}

int main(){
    cin.tie(nullptr)->sync_with_stdio(false);
    int t(1);
    cin >> t;
    while(t--)runcase();
}